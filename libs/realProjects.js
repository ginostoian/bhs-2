export const formatPrice = (n) => `£${Math.round(n).toLocaleString("en-GB")}`;

// Jobs where this is the main service come first, then jobs that included it.
export const projectsFor = (service, limit = 6) =>
  realProjects
    .filter((p) => p.services.includes(service))
    .sort((a, b) => a.services.indexOf(service) - b.services.indexOf(service))
    .slice(0, limit);

export const projectsInPostcodes = (prefixes = [], limit = 4) =>
  realProjects
    .filter((p) => prefixes.some((x) => p.postcode.startsWith(x)))
    .slice(0, limit);
